export const TIME_STEP_TOLERANCE = 0.02; // estimated time-stepping error of the peak, as a fraction of its rise
export const ENERGY_BALANCE_TOLERANCE = 0.03; // of the energy deposited, from the output fields
export const CROSS_CHECK_SPATIAL_FACTOR = 3; // times the finite-volume solution's own spatial refinement difference
export const CROSS_CHECK_FLOOR = 0.02; // K
/** A generated pulse's lumped (adiabatic) fuel temperature against the pin's real average: as a fraction of the generator's temperature rise. */
export const GENERATOR_FEEDBACK_TOLERANCE = 0.02;
export const GENERATOR_FEEDBACK_FLOOR = 0.1; // K
/**
 * The cross-check bound is the smaller of the spatial allowance above and this fraction of the peak temperature rise: the two
 * solutions share the cell layout and the (first-order) time scheme, so they agree far more closely than either agrees with the
 * exact solution, and a 1% error in a property or in the power shows up as about 1% of the rise. 0.5% therefore detects it.
 */
export const CROSS_CHECK_RISE_FRACTION = 0.005;

/** A conductivity as the linear part the pin model keeps for callers that want {a, b}; the full law travels in fuelLaw / claddingLaw. */
const lin = (k: Conductivity): Linear => {
  if (k.kind === "constant") return { a: k.k, b: 0 };
  if (k.kind === "linear") return { a: k.a, b: k.b };
  if (k.kind === "uo2-nfi") {
    // not a line either: the chord between the ends of its range, as for the reciprocal law; the law itself travels in fuelLaw
    const klo = evaluate(lawOf(k), k.range[0]), khi = evaluate(lawOf(k), k.range[1]);
    const slope = (khi - klo) / (k.range[1] - k.range[0]);
    return { a: klo - slope * k.range[0], b: slope };
  }
  if (k.kind === "reciprocal") {
    // not a line: the chord between the ends of its range, for a caller that wants {a, b}; the law itself travels in fuelLaw / claddingLaw
    const klo = k.a / k.range[0] + k.b, khi = k.a / k.range[1] + k.b;
    const slope = (khi - klo) / (k.range[1] - k.range[0]);
    return { a: klo - slope * k.range[0], b: slope };
  }
  return { a: k.coefficients[0]!, b: k.coefficients[1]! };
};
const linC = (c: HeatCapacity): Linear => (c.kind === "constant" ? { a: c.c, b: 0 } : c.kind === "linear" ? { a: c.a, b: c.b } : { a: c.coefficients[0]!, b: c.coefficients[1]! });

/** The independent model of a normalized transient case. */
export function pinOf(c: NormalizedCase, cellFactor = 1): TransientPin {
  if (!c.transient || !c.fuelHeatCapacity || !c.claddingHeatCapacity) throw new Error("not a transient case");
  const { times, linearHeatRate } = c.transient;
  const power = (t: number) => {
    if (t <= times[0]!) return linearHeatRate[0]!;
    for (let i = 1; i < times.length; i++) {
      if (t <= times[i]!) return linearHeatRate[i - 1]! + ((linearHeatRate[i]! - linearHeatRate[i - 1]!) * (t - times[i - 1]!)) / (times[i]! - times[i - 1]!);
    }
    return linearHeatRate[linearHeatRate.length - 1]!;
  };
  return {
    ...(c.plate ? { slab: true } : {}),
    fuelInnerRadius: c.fuelInnerRadius,
    fuelRadius: c.fuelRadius,
    claddingInnerRadius: c.claddingInnerRadius,
    claddingOuterRadius: c.claddingOuterRadius,
    fuelCells: c.mesh.fuelCells * cellFactor,
    claddingCells: c.mesh.claddingCells * cellFactor,
    gapConductance: c.gapConductance,
    fuelK: lin(c.fuelConductivity),
    fuelLaw: lawOf(c.fuelConductivity),
    claddingK: lin(c.claddingConductivity),
    claddingLaw: lawOf(c.claddingConductivity),
    fuelC: linC(c.fuelHeatCapacity),
    claddingC: linC(c.claddingHeatCapacity),
    fuelCLaw: heatCapacityLaw(c.fuelHeatCapacity),
    claddingCLaw: heatCapacityLaw(c.claddingHeatCapacity),
    boundary: c.boundary.kind === "convective" ? { kind: "convective", bulkTemperature: c.boundary.bulkTemperature, heatTransferCoefficient: c.boundary.heatTransferCoefficient } : { kind: "surface-temperature", surfaceTemperature: c.boundary.surfaceTemperature },
    ...(c.transient?.boundaryHistory ? { boundaryAt: (tt: number) => boundaryAtTime(c.transient!.boundaryHistory!, tt) } : {}),
    power,
  };
}

/** Where a transient starts, on this case's mesh (or one refined by cellFactor): every cell's temperature (fuel inner to outer, then cladding inner to outer),
 *  the outer wall, and the hottest cell. A uniform start is the given temperature; a steady start is the independent solution's steady field at the stated
 *  linear heat rate with the case's own properties and boundary, which throws a RangeError (with the reason) when there is none. */
export interface InitialState {
  T: number[];
  wall: number;
  peak: number;
  fuelPeak: number;
}
export function initialState(c: NormalizedCase, cellFactor = 1): InitialState {
  const t = c.transient;
  if (!t) throw new Error("not a transient case");
  const nf = c.mesh.fuelCells * cellFactor;
  const n = nf + c.mesh.claddingCells * cellFactor;
  if (t.initial.kind === "uniform") {
    const T0 = t.initial.temperature;
    const b0 = t.boundaryHistory ? boundaryAtTime(t.boundaryHistory, 0) : c.boundary;
    return { T: new Array<number>(n).fill(T0), wall: b0.kind === "surface-temperature" ? b0.surfaceTemperature : T0, peak: T0, fuelPeak: T0 };
  }
  const s = steadyFv(pinOf(c, cellFactor), t.initial.linearHeatRate);
  return { T: s.T, wall: s.wall, peak: maxOf(s.T), fuelPeak: maxOf(s.T.slice(0, nf)) };
}

/** Volume-average temperature of the fuel from the cell temperatures (fuel inner to outer first; the cells are equal in radius, so their volumes are the annuli's). */
export function fuelMean(c: NormalizedCase, T: number[]): number {
  const nf = c.mesh.fuelCells;
  let num = 0;
  let den = 0;
  for (let i = 0; i < nf; i++) {
    const r0 = c.fuelInnerRadius + ((c.fuelRadius - c.fuelInnerRadius) * i) / nf;
    const r1 = c.fuelInnerRadius + ((c.fuelRadius - c.fuelInnerRadius) * (i + 1)) / nf;
    const v = r1 * r1 - r0 * r0;
    num += v * T[i]!;
    den += v;
  }
  return num / den;
}

/** Exact integral of the piecewise-linear power history from 0 to t (J/m). */
export function depositedEnergy(times: number[], q: number[], t: number): number {
  let e = 0;
  for (let i = 1; i < times.length; i++) {
    const a = times[i - 1]!;
    if (t <= a) break;
    const b = Math.min(times[i]!, t);
    const qb = q[i - 1]! + ((q[i]! - q[i - 1]!) * (b - a)) / (times[i]! - a);
    e += 0.5 * (q[i - 1]! + qb) * (b - a);
  }
  return e;
}

/** Run the independent solution for the case: the result at the output times, with the given step divisor and cell factor. */
export function independentSolution(c: NormalizedCase, stepFactor = 1, cellFactor = 1, trace = false): FvTransient {
  const tr = c.transient!;
  const start = tr.initial.kind === "uniform" ? { initialTemperature: tr.initial.temperature } : { initialField: initialState(c, cellFactor).T };
  return solveTransientFv(pinOf(c, cellFactor), { dt: tr.timeStep / stepFactor, steps: tr.steps * stepFactor, ...start, outputEvery: (tr.steps / tr.outputs) * stepFactor, trace });
}

/** The three independent runs the results need: same mesh and step (with its trace), double mesh (the spatial error of the independent solution), half step (the time error). */
export interface IndependentSet {
  fv: FvTransient;
  fv2: FvTransient;
  fvh: FvTransient;
}
/** Run them in this thread. The run manager runs them in a worker instead (independentRunner.ts) and hands the answer to buildTransientResults. */
export function computeIndependent(c: NormalizedCase): IndependentSet {
  return { fv: independentSolution(c, 1, 1, true), fv2: independentSolution(c, 1, 2), fvh: independentSolution(c, 2, 1, true) };
}

/**
 * The worst relative gap of the energy balance with a boundary history, against the largest energy exchanged ANYWHERE in the run. The stored and the rejected energy can pass through
 * zero (a pin that cools then warms) and the heat leaving can change within a few steps between outputs (the trapezoid of that interval misses up to half of its exchange), so a
 * gap is not judged against the energy exchanged at that moment. A local gross bound was tried (the Codex review of 2026-10-14 asked for one) and cannot be told from that
 * unresolved jump by energy alone (an early gap of the size of the early exchange is exactly what a jump inside the first output interval looks like); a wrong early FIELD is caught
 * by the cross-check, which compares every cell at every output, not by this balance.
 */
export function historyEnergyWorst(deposited: number[], stored: number[], rejected: number[]): number {
  const whole = Math.max(...deposited.map((d, j) => Math.max(d, Math.abs(rejected[j]!), Math.abs(stored[j]!))));
  if (!(whole > 0)) return 0;
  return Math.max(...deposited.map((d, j) => Math.abs(d - stored[j]! - rejected[j]!) / whole));
}

/** The step against half step difference over every cell and the outer wall at each output, and the largest excursion of any cell or the wall from its start (the scale of its bound). */
export function fieldTimeError(fv: FvTransient, fvh: FvTransient, init: { T: number[]; wall: number }): { err: number; scale: number } {
  let err = 0;
  let scale = 0;
  fv.states.forEach((s, j) => {
    const sf = fvh.states[j];
    if (!sf) return;
    s.T.forEach((x, i) => {
      err = Math.max(err, Math.abs(x - sf.T[i]!));
      scale = Math.max(scale, Math.abs(x - init.T[i]!));
    });
    err = Math.max(err, Math.abs(s.wall - sf.wall));
    scale = Math.max(scale, Math.abs(s.wall - init.wall));
  });
  return { err, scale };
}

/**
 * Build the transient results record. Throws ResultsError for anything that is not a complete, finite, consistent set of fields:
 * wrong cell count or write times, non-finite or non-positive temperatures, a file cut short, a missing wall value.
 */
/** At most 400 evenly indexed points of the integrated curve (the thinned history is the one the run used; this is for plotting). */
export function downsample(g: GeneratedPulse) {
  const n = g.trace.time.length;
  const step = Math.max(1, Math.ceil(n / 400));
  const idx: number[] = [];
  for (let i = 0; i < n; i += step) idx.push(i);
  if (idx[idx.length - 1] !== n - 1) idx.push(n - 1);
  const pick = (a: number[]) => idx.map((i) => a[i]!);
  return { time: pick(g.trace.time), power: pick(g.trace.power), reactivity: pick(g.trace.reactivity), fuelTemperature: pick(g.trace.fuelTemperature) };
}

/** What a stack adds to the tolerances of one slice's transient checks for the axial conduction (src/core/stackTransientResults.ts): kelvin on the cross-check and a relative amount on the energy balance. */
export interface TransientAllowance {
  field: number;
  energy: number;
}

export function buildTransientResults(c: NormalizedCase, input: TransientInput, independent?: IndependentSet, allow?: TransientAllowance): TransientResultsRecord {
  const tr = c.transient;
  if (!tr || !c.fuelHeatCapacity || !c.claddingHeatCapacity) bad("the case is not a transient");
  const t = tr!;
  const nf = c.mesh.fuelCells;
  const nc = c.mesh.claddingCells;
  const n = nf + nc;
  if (input.fields.length !== t.outputs) bad(`expected ${t.outputs} write times after 0, found ${input.fields.length}`);
  const dtOut = (t.steps / t.outputs) * t.timeStep;
  input.fields.forEach((f, k) => {
    const want = (k + 1) * dtOut;
    if (!(Math.abs(f.time - want) <= 1e-9 * t.endTime)) bad(`write time ${k + 1} is ${f.time} s, expected ${want} s`);
  });

  const Craw = parseVectorField(input.C, "C");
  if (Craw.length !== n) bad(`C has ${Craw.length} cells, expected ${n}`);
  assertWholeFoamFile(input.C, "C");
  const r = Craw.map((p) => Math.hypot(p[0]!, p[1]!));
  const eps = 1e-9;
  r.forEach((x, i) => {
    if (x > c.claddingOuterRadius + eps) bad(`cell ${i} is outside the pin (r = ${x} m)`);
    if (!(x < c.fuelRadius || x > c.claddingInnerRadius)) bad(`cell ${i} has its centre in the gap or on an interface (r = ${x} m)`);
    if (x < c.fuelInnerRadius + eps) bad(`cell ${i} has its centre inside the central hole (r = ${x} m)`);
  });
  const order = r.map((x, i) => ({ x, i })).sort((a, b) => a.x - b.x);
  const fuelIdx = order.filter((o) => o.x < c.fuelRadius).map((o) => o.i);
  const cladIdx = order.filter((o) => o.x > c.claddingInnerRadius).map((o) => o.i);
  if (fuelIdx.length !== nf || cladIdx.length !== nc) bad("cell centres do not split into the expected fuel and cladding counts");
  const idx = [...fuelIdx, ...cladIdx];
  const cells: TransientRadialCell[] = idx.map((i, j) => ({ r: r[i]!, region: j < nf ? "fuel" : "cladding" }));
  // The cell centres OFFBEAT writes are the volume centroids of the wedge cells; they must be where THIS case's mesh puts them, or the
  // profile, the stored energy and the independent comparison would all be about a different pin.
  const centroid = (a: number, b: number) => geometryOf(c.plate).centroid(a, b);
  const dFuel = (c.fuelRadius - c.fuelInnerRadius) / nf;
  const dClad = (c.claddingOuterRadius - c.claddingInnerRadius) / nc;
  cells.forEach((cell, j) => {
    const k0 = j < nf ? j : j - nf;
    const a = j < nf ? c.fuelInnerRadius + k0 * dFuel : c.claddingInnerRadius + k0 * dClad;
    const d = j < nf ? dFuel : dClad;
    const want = centroid(a, a + d);
    if (!(Math.abs(cell.r - want) <= 1e-3 * d + 1e-9)) bad(`cell ${j}: the centre is at r = ${cell.r} m but this case's mesh puts it at ${want} m`);
  });
  for (let j = 1; j < nf; j++) if (!(cells[j]!.r - cells[j - 1]!.r > 1e-12)) bad("two fuel cells share a centre");
  for (let j = nf + 1; j < n; j++) if (!(cells[j]!.r - cells[j - 1]!.r > 1e-12)) bad("two cladding cells share a centre");

  const times = [0, ...input.fields.map((f) => f.time)];
  const init = initialState(c);
  const profiles: number[][] = [init.T.slice()];
  const walls: number[] = [init.wall];
  for (const [k, f] of input.fields.entries()) {
    const T = parseScalarField(f.T, "T");
    if (T.length !== n) bad(`time ${f.time}: expected ${n} cells, found ${T.length}`);
    if (!/\bboundaryField\b/.test(f.T)) bad(`time ${f.time}: field T has no boundaryField (the file is cut short)`);
    const wall = parsePatchValue(f.T, "cladOuter");
    if (wall === null) bad(`time ${f.time}: field T has no value for the cladOuter patch`);
    if (!(wall! > 0)) bad(`time ${f.time}: the outer wall temperature ${wall} K is not above 0 K`);
    assertWholeFoamFile(f.T, "T");
    T.forEach((x, i) => {
      if (!(x > 0)) bad(`time ${f.time}, cell ${i}: temperature ${x} K is not above 0 K`);
    });
    profiles.push(idx.map((i) => T[i]!));
    walls.push(wall!);
    void k;
  }

  // --- series
  const pin = pinOf(c);
  const series: TransientSeries = { time: times, power: times.map((tt) => pin.power(tt)), deposited: times.map((tt) => depositedEnergy(t.times, t.linearHeatRate, tt)), peakT: [], fuelSurfaceCellT: [], claddingInnerCellT: [], claddingOuterWallT: walls, stored: [], rejected: [] };
  const hist = t.boundaryHistory;
  const geo = geometryOf(c.plate);
  const outflow = (prof: number[], wall: number, at = 0) => {
    if (hist && hist.kind === "convective") {
      const b = boundaryAtTime(hist, at) as { heatTransferCoefficient: number; bulkTemperature: number };
      return b.heatTransferCoefficient * geo.area(c.claddingOuterRadius) * (wall - b.bulkTemperature);
    }
    if (c.boundary.kind === "convective") return c.boundary.heatTransferCoefficient * geo.area(c.claddingOuterRadius) * (wall - c.boundary.bulkTemperature);
    const kk = lawOf(c.claddingConductivity);
    const Tl = prof[n - 1]!;
    // the heat through the last half cell: 2 pi (K(T_last) - K(T_wall)) / ln(Ro / r_last), K the primitive of k(T); for a linear law that is k at the mean temperature times the difference
    return (primitive(kk, Tl) - primitive(kk, wall)) / geo.resist(cells[n - 1]!.r, c.claddingOuterRadius, 1);
  };
  let rej = 0;
  profiles.forEach((p, k) => {
    series.peakT.push(maxOf(p));
    series.fuelSurfaceCellT.push(p[nf - 1]!);
    series.claddingInnerCellT.push(p[nf]!);
    series.stored.push(storedEnergy(pin, p, t.initial.kind === "uniform" ? t.initial.temperature : init.T));
    if (k > 0 && hist && hist.kind === "convective") {
      // a film coefficient that changes between two outputs: the wall temperature is taken linear between them and the heat h(t) A (wall - T_bulk(t)) is integrated finely (Simpson), so
      // a step in the film between outputs is not lost to the trapezoid of the two output values
      const t0 = times[k - 1]!;
      const t1 = times[k]!;
      const NSUB = 400;
      let acc = 0;
      for (let s = 0; s <= NSUB; s++) {
        const at = t0 + ((t1 - t0) * s) / NSUB;
        const w = walls[k - 1]! + ((walls[k]! - walls[k - 1]!) * (at - t0)) / (t1 - t0);
        acc += (s === 0 || s === NSUB ? 1 : s % 2 ? 4 : 2) * outflow(p, w, at);
      }
      rej += (acc * (t1 - t0)) / (3 * NSUB);
    } else if (k > 0) rej += 0.5 * (outflow(profiles[k - 1]!, walls[k - 1]!, times[k - 1]!) + outflow(p, walls[k]!, times[k]!)) * (times[k]! - times[k - 1]!);
    series.rejected.push(rej);
  });

  const checks: Check[] = [];
  /** Rise of the hottest cell over the outputs. The check thresholds use the larger rise over every step of the independent solution. */
  const outputRise = maxOf(series.peakT) - init.peak;
  let peakRise = outputRise;

  // energy balance from the output fields
  const k = times.length - 1;
  // From a uniform start the balance is judged against the energy deposited so far. From a steady operating state the heat made and the heat leaving are both large and
  // nearly equal (and a shutdown deposits nothing), so it is judged against the largest of the energy deposited, rejected and stored so far.
  const steadyStart = t.initial.kind === "steady" || hist !== undefined;
  // With a boundary history the stored and the rejected energy can pass through zero (a pin that cools and then warms), and the heat leaving can jump within a few steps while the
  // outputs are seconds apart (a wall that starts to move: the trapezoid of the first interval misses half of it). The gap is then judged against the largest energy exchanged
  // anywhere in the run, not the value at that moment.
  const throughput = (j: number) => (hist ? 1 : steadyStart ? Math.max(series.deposited[j]!, series.rejected[j]!, Math.abs(series.stored[j]!)) : series.deposited[j]!);
  if (throughput(k) > 0) {
    const worst = hist
      ? historyEnergyWorst(series.deposited, series.stored, series.rejected)
      : Math.max(...times.map((_, j) => (throughput(j) > 0 ? Math.abs(series.deposited[j]! - series.stored[j]! - series.rejected[j]!) / throughput(j) : 0)));
    checks.push({ id: "energyBalance", label: "Energy balance (deposited = stored + rejected, from the outputs)", value: worst, unit: "relative", verdict: worst <= ENERGY_BALANCE_TOLERANCE + (allow?.energy ?? 0) ? "pass" : "fail", note: `largest relative gap over the outputs; threshold ${(100 * (ENERGY_BALANCE_TOLERANCE + (allow?.energy ?? 0))).toPrecision(3)}% of the ${hist ? "largest of the energy deposited, rejected and stored anywhere in the run (a boundary history: the energies can cross zero, and the heat leaving can change within a few steps between outputs)" : steadyStart ? "largest of the energy deposited, rejected and stored so far (the run starts from a steady operating state)" : "energy deposited so far"}. It includes the first-order error of depositing the source at the new time (about 1/N of the energy over a ramp of N steps) and a trapezoid over the output times for the heat leaving` });
  }

  // independent solution: same mesh and step (cross-check), double mesh (spatial error of the independent solution), half step (time error)
  const { fv, fv2, fvh } = independent ?? computeIndependent(c);
  if (fv.states.length !== times.length) bad("the independent solution has a different number of outputs");
  peakRise = Math.max(outputRise, maxOf(fv.trace!.peakByStep) - init.peak);
  // The thresholds below are fractions of how far the pin's temperatures move. From a uniform start that is the rise; from a steady operating state the
  // peak may hardly rise (a hold, a scram) while the whole field changes, so the scale is the peak ever reached above the coolant (or prescribed wall) temperature.
  const outerRef = c.boundary.kind === "convective" ? c.boundary.bulkTemperature : c.boundary.surfaceTemperature;
  const baseScale = t.initial.kind === "steady" ? Math.max(peakRise, init.peak + peakRise - outerRef) : peakRise;
  // a changing boundary can only cool the pin or warm it with no heat source at all: the scale is then the largest excursion of the peak from its start, up or down
  const scaleRise = hist ? Math.max(baseScale, init.peak - minOf(fv.trace!.peakByStep), maxOf(fv.trace!.peakByStep) - init.peak) : baseScale;
  const volumeWeights = (cellsPerRegion: number, rIn: number, rOut: number) => {
    const faces = Array.from({ length: cellsPerRegion + 1 }, (_, i) => rIn + ((rOut - rIn) * i) / cellsPerRegion);
    return faces;
  };
  const fuelFaces2 = volumeWeights(2 * nf, c.fuelInnerRadius, c.fuelRadius);
  const cladFaces2 = volumeWeights(2 * nc, c.claddingInnerRadius, c.claddingOuterRadius);
  const subVol = (faces: number[], j: number) => faces[j + 1]! ** 2 - faces[j]! ** 2;
  let spatial = 0;
  let cross = 0;
  let crossAt = 0;
  let timeErr = 0;
  fv.states.forEach((s, j) => {
    for (let i = 0; i < n; i++) {
      const fine = fv2.states[j]!.T;
      let avg: number;
      if (i < nf) {
        const a = subVol(fuelFaces2, 2 * i);
        const b = subVol(fuelFaces2, 2 * i + 1);
        avg = (a * fine[2 * i]! + b * fine[2 * i + 1]!) / (a + b);
      } else {
        const ic = i - nf;
        const a = subVol(cladFaces2, 2 * ic);
        const b = subVol(cladFaces2, 2 * ic + 1);
        avg = (a * fine[2 * nf + 2 * ic]! + b * fine[2 * nf + 2 * ic + 1]!) / (a + b);
      }
      spatial = Math.max(spatial, Math.abs(s.T[i]! - avg));
      const d = Math.abs(profiles[j]![i]! - s.T[i]!);
      if (d > cross) {
        cross = d;
        crossAt = times[j]!;
      }
    }
    // the outer wall as well: it is a patch value that no cell check would catch
    if (j > 0) {
      const dw = Math.abs(walls[j]! - s.wall);
      if (dw > cross) {
        cross = dw;
        crossAt = times[j]!;
      }
    }
  });
  // the time-step error over EVERY step of the run, not only at the saved outputs (a sparse output would hide a pulse that is not resolved)
  const coarse = fv.trace!.peakByStep;
  const fine = fvh.trace!.peakByStep;
  for (let j = 0; j < coarse.length; j++) timeErr = Math.max(timeErr, Math.abs(coarse[j]! - fine[2 * j]!));
  // A boundary history can act on the cladding while the hottest cell, in the fuel, hardly moves: the step against half step difference is then also taken over every cell and the
  // outer wall at each output, against the largest excursion of any cell from its start (Codex review 2026-10-14).
  const field = hist ? fieldTimeError(fv, fvh, init) : { err: 0, scale: 0 };
  const fieldErr = field.err;
  const fieldScale = field.scale;
  const crossBound = Math.min(CROSS_CHECK_SPATIAL_FACTOR * spatial, CROSS_CHECK_RISE_FRACTION * Math.max(scaleRise, 1)) + CROSS_CHECK_FLOOR + (allow?.field ?? 0);
  checks.push({ id: "crossCheckFv", label: "OFFBEAT vs the independent finite-volume solution (max cell deviation)", value: cross, unit: "K", verdict: cross <= crossBound ? "pass" : "fail", note: `largest at t = ${crossAt} s; bound ${crossBound.toFixed(3)} K = min(${CROSS_CHECK_SPATIAL_FACTOR} x ${spatial.toFixed(3)} K [the independent solution's own change when its cells are halved], ${CROSS_CHECK_RISE_FRACTION * 100}% of the peak rise) + ${CROSS_CHECK_FLOOR} K${allow && allow.field > 0 ? ` + ${allow.field.toPrecision(3)} K for the heat flow along the pin (an axial stack)` : ""}` });
  // the independent run with half the step shows how much the time stepping (first order, as OFFBEAT's) is worth
  const timeBound = TIME_STEP_TOLERANCE * Math.max(scaleRise, 1);
  const fieldBound = TIME_STEP_TOLERANCE * Math.max(fieldScale, 1);
  const timeOk = timeErr <= timeBound && (!hist || fieldErr <= fieldBound);
  checks.push({ id: "timeStep", label: "Time-stepping error of the peak temperature (step vs half step)", value: hist ? Math.max(timeErr, fieldErr) : timeErr, unit: "K", verdict: timeOk ? "pass" : "fail", note: `the peak changes by at most ${timeErr.toFixed(3)} K, at any step of the run, when the step is halved; threshold ${TIME_STEP_TOLERANCE * 100}% of the peak rise (${timeBound.toFixed(2)} K).${hist ? ` With a boundary history every cell and the outer wall are compared at each output too: at most ${fieldErr.toFixed(3)} K, threshold ${TIME_STEP_TOLERANCE * 100}% of the largest excursion of any cell (${fieldBound.toFixed(2)} K).` : ""} If it fails, shorten the time step` });

  if (c.boundary.kind === "surface-temperature") {
    const wanted = (tt: number) => (hist && hist.kind === "surface-temperature" ? (boundaryAtTime(hist, tt) as { surfaceTemperature: number }).surfaceTemperature : (c.boundary as { surfaceTemperature: number }).surfaceTemperature);
    const d = maxOf(walls.map((w, j) => Math.abs(w - wanted(times[j]!))));
    checks.push({ id: "wallTemperature", label: "Outer wall temperature vs the prescribed value", value: d, unit: "K", verdict: d < 0.05 ? "pass" : "fail", note: "threshold 0.05 K at every output" + (hist ? " (against the boundary history at each output time)" : "") });
  }

  // a pulse generated by point kinetics: its feedback used the fuel's temperature if the heat stayed where it was made; the real pin conducts it away,
  // so the model is valid only while that is small. The check compares the two averages at every output.
  const gen = t.generated;
  if (gen) {
    const gt = gen.trace.time;
    const at = (time: number) => {
      let i = 1;
      while (i < gt.length - 1 && gt[i]! < time) i++;
      const f = gt[i]! === gt[i - 1]! ? 0 : (time - gt[i - 1]!) / (gt[i]! - gt[i - 1]!);
      return gen.trace.fuelTemperature[i - 1]! + f * (gen.trace.fuelTemperature[i]! - gen.trace.fuelTemperature[i - 1]!);
    };
    let worstGen = 0;
    let worstAt = 0;
    profiles.forEach((p, j) => {
      const d = Math.abs(fuelMean(c, p) - at(times[j]!));
      if (d > worstGen) {
        worstGen = d;
        worstAt = times[j]!;
      }
    });
    const genBound = GENERATOR_FEEDBACK_TOLERANCE * gen.summary.peakFuelRise + GENERATOR_FEEDBACK_FLOOR;
    checks.push({ id: "pulseGenerator", label: "Generated pulse: feedback temperature vs the pin's real fuel average (max over the outputs)", value: worstGen, unit: "K", verdict: worstGen <= genBound ? "pass" : "fail", note: `the point-kinetics feedback used the fuel's average temperature as if no heat left it; the pin's own average differs from it by at most ${worstGen.toFixed(3)} K, at t = ${worstAt} s; bound ${genBound.toFixed(3)} K = ${GENERATOR_FEEDBACK_TOLERANCE * 100}% of the generator's peak rise (${gen.summary.peakFuelRise.toFixed(1)} K) + ${GENERATOR_FEEDBACK_FLOOR} K. If it fails, the heat left the fuel too fast for the generated pulse to be valid over this window: shorten the run to the pulse` });
  }

  // property ranges
  const findings: DomainFinding[] = [];
  const range = (region: "fuel" | "cladding", lo: number, hi: number, stated: [number, number]) => {
    if (lo < stated[0] || hi > stated[1]) findings.push({ region, produced: [lo, hi], validRange: stated });
  };
  /** Extremes of a region over every saved output AND over every step of the independent solution (an excursion between outputs counts). */
  const extremes = (from: number, to: number, traceMin: number, traceMax: number) => {
    let lo = traceMin;
    let hi = traceMax;
    for (const p of profiles) {
      for (let i = from; i < to; i++) {
        if (p[i]! < lo) lo = p[i]!;
        if (p[i]! > hi) hi = p[i]!;
      }
    }
    return { lo, hi };
  };
  const rangesOf = (kk: Conductivity, cc: HeatCapacity | undefined, region: "fuel" | "cladding", e: { lo: number; hi: number }) => {
    const kr = rangeOf(kk);
    if (kr) range(region, e.lo, e.hi, kr);
    const cr = cc && heatCapacityRange(cc);
    if (cr) range(region, e.lo, e.hi, cr);
  };
  rangesOf(c.fuelConductivity, c.fuelHeatCapacity, "fuel", extremes(0, nf, fv.trace!.fuelMin, fv.trace!.fuelMax));
  rangesOf(c.claddingConductivity, c.claddingHeatCapacity, "cladding", extremes(nf, n, fv.trace!.claddingMin, fv.trace!.claddingMax));
  const anyLinear = rangeOf(c.fuelConductivity) !== undefined || rangeOf(c.claddingConductivity) !== undefined || c.fuelHeatCapacity!.kind !== "constant" || c.claddingHeatCapacity!.kind !== "constant";
  const domain = { verdict: (findings.length === 0 ? "in-domain" : "out-of-domain") as "in-domain" | "out-of-domain", findings };
  if (anyLinear) {
    checks.push({ id: "propertyRange", label: "Property laws within their stated ranges", value: null, unit: "", verdict: findings.length === 0 ? "pass" : "fail", note: findings.length === 0 ? "all cell temperatures inside the stated ranges at every output and at every step of the independent solution" : findings.map((f) => `${f.region}: ${f.produced.map((x) => x.toFixed(0)).join("-")} K outside ${f.validRange.join("-")} K`).join("; ") + ". A law was extrapolated; this result is out-of-domain." });
  }

  checks.push(...fitChecks(c));
  if (c.limits) {
    const hottest = (p: number[], from: number, to: number) => p.slice(from, to).reduce((m, x) => (x > m ? x : m), -Infinity);
    const observed = profiles.map((p, j) => ({ time: times[j]!, fuelMax: hottest(p, 0, nf), claddingMax: hottest(p, nf, p.length) }));
    const tr = fv.trace!;
    const independent = tr.fuelByStep.map((f, j) => ({ time: j * t.timeStep, fuelMax: f, claddingMax: tr.claddingByStep[j]! }));
    checks.push(...limitChecks(c.limits, observed, independent));
  }
  for (const ch of checks) if (ch.value !== null && !Number.isFinite(ch.value)) bad(`check ${ch.id} is not a finite number (${ch.value})`);
  const jMax = series.peakT.indexOf(maxOf(series.peakT));
  return {
    schema: "feed.results/0.2",
    kind: "transient",
    caseId: c.caseId,
    initialTemperature: init.peak,
    initialState: t.initial.kind === "uniform" ? { kind: "uniform", temperature: t.initial.temperature } : { kind: "steady", linearHeatRate: t.initial.linearHeatRate, peakTemperature: init.peak },
    times,
    cells,
    profiles,
    series,
    ...(gen ? { generator: { kind: "point-kinetics" as const, summary: gen.summary, curve: downsample(gen) } } : {}),
    summary: { maxT: series.peakT[jMax]!, timeOfMaxT: times[jMax]!, maxRise: outputRise, finalPeakT: series.peakT[times.length - 1]!, finalTime: times[times.length - 1]! },
    checks,
    domain,
    thermalOnly: THERMAL_ONLY_TEXT,
  };
}
